		/// <summary>
		/// Tensor product of the Gauss-Legendre rule with <paramref name="n"/> points: csi varies in the outer loop, eta in the inner one
		/// </summary>
		private static GaussPoint[] TensorProduct(int n)
		{
			GaussLegendre(n, out double[] nodes, out double[] weights);

			var points = new GaussPoint[n * n];
			for (int i = 0; i < n; i++)
			{
				for (int j = 0; j < n; j++)
					points[i * n + j] = new GaussPoint(nodes[i], nodes[j], weights[i] * weights[j], i * n + j + 1);
			}
			return points;
		}

		/// <summary>
		/// Nodes (increasing) and weights of the Gauss-Legendre rule on [-1, 1]: roots of the Legendre polynomial by Newton's method
		/// </summary>
		private static void GaussLegendre(int n, out double[] nodes, out double[] weights)
		{
			nodes = new double[n];
			weights = new double[n];

			for (int i = 0; i < (n + 1) / 2; i++)
			{
				double x = System.Math.Cos(System.Math.PI * (i + 0.75) / (n + 0.5));
				double derivative = 0;
				for (int iteration = 0; iteration < 100; iteration++)
				{
					// P_n(x) and its derivative by the recurrence
					double p0 = 1.0, p1 = x;
					for (int k = 2; k <= n; k++)
					{
						double p2 = ((2 * k - 1) * x * p1 - (k - 1) * p0) / k;
						p0 = p1;
						p1 = p2;
					}
					derivative = n * (x * p1 - p0) / (x * x - 1.0);

					double dx = p1 / derivative;
					x -= dx;
					if (System.Math.Abs(dx) < 1E-16)
						break;
				}

				double weight = 2.0 / ((1.0 - x * x) * derivative * derivative);
				nodes[i] = -x;
				nodes[n - 1 - i] = x;
				weights[i] = weight;
				weights[n - 1 - i] = weight;
			}
		}
